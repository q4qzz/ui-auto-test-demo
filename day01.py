# -*- coding: utf-8 -*-
"""Day 1 练习：我的第一个 Python 程序。

【你要做的事】
1. 把下面的 name 改成你自己的名字（引号要保留）
2. 把 days 改成你给自己的天数
3. 按 Ctrl+S 保存
4. 回到文件夹，双击 run_day01.bat 看结果

【看不懂没关系】
每一行后面的 # 号后面是解释，先看懂大意就行。
"""

print("=" * 40)

# ---- 第 1 部分：变量 ----
# 变量就是一个"盒子"，把东西装进去，起个名字方便后面用
name = "leh"      # ← 改这里，换成你的名字
days = 30              # ← 改这里，换成你打算投入的天数

print("你好，" + name)
print("我要用", days, "天拿到实习 offer")

print("=" * 40)

# ---- 第 2 部分：循环 ----
# for 就是"重复做几次"
# range(1, 6) 表示从 1 数到 5（注意：不包含 6，这是 Python 的规矩）
for day in range(1, 6):
    print("第", day, "天：继续学 Python")

print("=" * 40)

# ---- 第 3 部分：条件判断 ----
# if 就是"如果……就……，否则……"
if days >= 30:
    print("时间够用，按计划走")
else:
    print("时间紧张，要加速了")

print("=" * 40)
print("程序结束。你已经跑通第一个 Python 程序了。")
