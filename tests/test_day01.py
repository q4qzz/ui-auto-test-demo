# -*- coding: utf-8 -*-
"""Day 1 第二条：我自己写的第一条测试用例。

【什么叫测试用例？】
一句话：就是"我断言 XXX 应该等于 YYY"。

pytest 会帮你自动检查这句话：
    说得对  ->  显示 PASSED（通过）
    说错了  ->  显示 FAILED（失败）

【你要做的事——故意让它失败一次】
1. 找到下面那行 `assert result == 4`
2. 把 4 改成 5
3. 按 Ctrl+S 保存
4. 回到主文件夹，双击 run_tests.bat
5. 认真看那段红色的 FAILED，它告诉了你三件事：
       - 哪条用例失败了
       - 你断言的是什么
       - 实际值是多少
6. 看明白后，把 5 改回 4，再跑一次，看它变回绿色

【为什么故意让它失败？】
测试工程师的价值，就是"找出不对的地方"。
一个从来不会红的测试，等于没有测试。
"""


def test_my_first_case():
    """我自己写的第一条测试用例。"""
    result = 2 + 2
    assert result == 4      # ← 把这里的 4 改成 5，然后保存、重跑
